// switch
function divisionUsingSwitch(num1, num2)
{
    switch(num1/num2){
        case 100:
        console.log("first case")
        break;
        case 50:
        console.log("second case")
        break;
        case 20:
        console.log("third case")
        break;
        default:
            console.log("default case")
    }
}

divisionUsingSwitch(100,5)
